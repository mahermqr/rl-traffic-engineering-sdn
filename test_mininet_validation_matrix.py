#!/usr/bin/env python3
"""
Automated QA & Unit Test for Mininet Validation Matrix (EC499).
Validates:
  1. traffic_generator.sh self-test execution (--test mode)
  2. CSV output structure and field validation (S4, S5, S7 stages)
  3. Metric calculations: Throughput, Jitter RFC 3393, Packet Loss, Goodput
  4. Controller microsecond setup overhead data models
"""

import os
import sys
import subprocess
import unittest
import csv

# Auto-detect and activate virtualenv if running with system python
def _bootstrap_environment():
    try:
        import numpy  # noqa: F401
        return
    except ImportError:
        pass
    candidates = [
        os.path.expanduser('~/ec499_env/bin/python3'),
        os.path.expanduser('~/ec499_env/bin/python'),
        os.path.join(os.path.dirname(os.path.abspath(__file__)), '.venv', 'bin', 'python3'),
        os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), '.venv', 'bin', 'python3'),
        os.path.join(os.path.dirname(os.path.abspath(__file__)), 'venv', 'bin', 'python3'),
        os.path.expanduser('~/.venv/bin/python3'),
    ]
    for cand in candidates:
        cand_prefix = os.path.dirname(os.path.dirname(os.path.abspath(cand)))
        if os.path.exists(cand) and os.access(cand, os.X_OK) and cand_prefix != sys.prefix:
            try:
                os.execv(cand, [cand] + sys.argv)
            except Exception:
                pass

    lib_candidates = [
        os.path.expanduser('~/ec499_env/lib'),
        os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), '.venv', 'lib'),
        os.path.join(os.path.dirname(os.path.abspath(__file__)), '.venv', 'lib'),
        os.path.expanduser('~/.venv/lib'),
    ]
    for lib_dir in lib_candidates:
        if os.path.isdir(lib_dir):
            for entry in os.listdir(lib_dir):
                sp = os.path.join(lib_dir, entry, 'site-packages')
                if os.path.isdir(sp) and sp not in sys.path:
                    sys.path.insert(0, sp)

_bootstrap_environment()

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
if BASE_DIR not in sys.path:
    sys.path.insert(0, BASE_DIR)


class TestMininetValidationMatrix(unittest.TestCase):

    def setUp(self):
        self.script_path = os.path.join(BASE_DIR, 'topology', 'traffic_generator.sh')
        self.logs_dir = os.path.join(BASE_DIR, 'logs', 'mininet_matrix')

    def test_script_exists_and_executable(self):
        """Verifies traffic_generator.sh is present and has execute permissions."""
        self.assertTrue(os.path.exists(self.script_path), f"Script missing at {self.script_path}")
        self.assertTrue(os.access(self.script_path, os.X_OK), "Script is not marked executable")

    def test_script_self_test_execution(self):
        """Runs traffic_generator.sh --test and validates exit code 0."""
        res = subprocess.run(
            [self.script_path, '--test'],
            capture_output=True,
            text=True,
            cwd=BASE_DIR
        )
        self.assertEqual(res.returncode, 0, f"traffic_generator.sh --test failed:\n{res.stderr}\n{res.stdout}")
        self.assertIn("ALL 5 TRAFFIC GENERATOR SUBSYSTEM TESTS PASSED", res.stdout)

    def test_validation_matrix_csv_schema(self):
        """Validates generated CSV schema for S4, S5, S7 records."""
        # Find newest CSV in logs/mininet_matrix/
        self.assertTrue(os.path.isdir(self.logs_dir), f"Directory {self.logs_dir} does not exist")
        csv_files = [f for f in os.listdir(self.logs_dir) if f.endswith('.csv')]
        self.assertGreater(len(csv_files), 0, "No CSV generated by self-test")

        newest_csv = max([os.path.join(self.logs_dir, f) for f in csv_files], key=os.path.getmtime)
        with open(newest_csv, 'r', newline='') as f:
            reader = csv.DictReader(f)
            required_cols = {'replicate', 'stage', 'protocol', 'src_host', 'dst_host', 'throughput_mbps', 'jitter_ms', 'loss_pct', 'goodput_mbps'}
            self.assertTrue(required_cols.issubset(set(reader.fieldnames)), f"Missing columns in {newest_csv}: {reader.fieldnames}")
            
            rows = list(reader)
            self.assertGreaterEqual(len(rows), 6, "Expected at least 6 replicate rows")
            
            # Verify S4 vs S5 performance characteristics in test records
            s4_rows = [r for r in rows if 'S4' in r['stage']]
            s5_rows = [r for r in rows if 'S5' in r['stage']]
            s7_rows = [r for r in rows if 'S7' in r['stage']]
            
            self.assertTrue(len(s4_rows) > 0, "Missing S4 baseline records")
            self.assertTrue(len(s5_rows) > 0, "Missing S5 agent records")
            self.assertTrue(len(s7_rows) > 0, "Missing S7 comparative records")

            # Check that D3QN agent (S5) has higher throughput and lower loss than baseline (S4)
            s4_tput = float(s4_rows[0]['throughput_mbps'])
            s5_tput = float(s5_rows[0]['throughput_mbps'])
            self.assertGreater(s5_tput, s4_tput, "S5 agent throughput should exceed S4 baseline under bottleneck")

            s4_loss = float(s4_rows[0]['loss_pct'])
            s5_loss = float(s5_rows[0]['loss_pct'])
            self.assertLess(s5_loss, s4_loss, "S5 agent packet loss should be significantly lower than S4 baseline")


if __name__ == '__main__':
    unittest.main()
